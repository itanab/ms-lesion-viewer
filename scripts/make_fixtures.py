"""Generate synthetic test fixtures (no real patient data) into a directory.

Usage: backend/.venv/bin/python scripts/make_fixtures.py <out_dir>
"""
import gzip
import sys
from pathlib import Path

import nibabel as nib
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))
from app.imaging import phantom  # noqa: E402

SHAPE, SPACING = (64, 72, 40), (1.0, 1.0, 2.5)


def save(path: Path, arr, aff, dtype):
    img = nib.Nifti1Image(np.asarray(arr).astype(dtype), aff)
    img.header.set_xyzt_units("mm")
    nib.save(img, str(path))


def perf(out: Path) -> None:
    """256 x 256 x 180 reference volume (the spec's performance fixture)."""
    shape, sp = (256, 256, 180), (0.9, 0.9, 1.2)
    aff = phantom.centred_affine(shape, sp, np.diag([-1.0, -1.0, 1.0]))
    vol, mask = phantom.make_phantom(shape, aff)
    save(out / "perf_mri.nii.gz", vol, aff, np.float32)
    save(out / "perf_mask.nii.gz", mask, aff, np.uint8)


def main(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    if len(sys.argv) > 2 and sys.argv[2] == "--perf":
        return perf(out)
    aff = phantom.centred_affine(SHAPE, SPACING, np.diag([-1.0, -1.0, 1.0]))     # LPS storage, like open_ms_data
    vol, mask = phantom.make_phantom(SHAPE, aff)
    save(out / "mri.nii.gz", vol, aff, np.float32)
    save(out / "mask.nii.gz", mask, aff, np.uint8)
    shifted = aff.copy(); shifted[0, 3] += 1.0
    save(out / "mask_shifted.nii.gz", mask, shifted, np.uint8)
    offset = aff.copy(); offset[:3, 3] += 0.5 * np.array(SPACING)
    save(out / "mask_halfvoxel.nii.gz", mask, offset, np.uint8)
    save(out / "mask_prob.nii.gz", mask.astype(np.float32) * 0.6, aff, np.float32)
    save(out / "mask_empty.nii.gz", np.zeros(SHAPE), aff, np.uint8)
    dense = np.zeros(SHAPE, np.uint8)                                            # 30 separate footprints on one slice
    for i in range(6):
        for j in range(5):
            dense[6 + i * 9 : 8 + i * 9, 8 + j * 12 : 10 + j * 12, 20] = 1
    save(out / "mask_dense.nii.gz", dense, aff, np.uint8)
    raw = (out / "mri.nii.gz").read_bytes()
    (out / "corrupt.nii.gz").write_bytes(raw[: len(raw) // 2])
    (out / "dicom_like.nii").write_bytes(b"\0" * 128 + b"DICM" + b"\0" * 400)
    (out / "readme.txt").write_text("Synthetic fixtures generated by scripts/make_fixtures.py\n")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
